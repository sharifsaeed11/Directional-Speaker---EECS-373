#define PWM_PERIOD_TICKS 3600
static uint32_t duty_to_cr(float duty)
{
  if (duty < 0.0f) { duty = 0.0f; }
  if (duty > 1.0f) { duty = 1.0f; }
  uint32_t on_ticks = (uint32_t)((duty * (float)PWM_PERIOD_TICKS) + 0.5f);
  if (on_ticks > PWM_PERIOD_TICKS) { on_ticks = PWM_PERIOD_TICKS; }
  return PWM_PERIOD_TICKS - on_ticks;
}

void fill_buffer_with_sine(){
    const float two_pi = 6.28318530718f;
    #define BLOCK_SIZE 256
    for (uint32_t k = 0U; k < BLOCK_SIZE; k++) {
        float s = sinf(two_pi * ((float)k/2.0f)/( (float)BLOCK_SIZE));
        uint32_t duty = duty_to_cr(0.50f + (0.40f * s));
        audio_buffer_0[0][k] = duty / 2;
    }

    for (uint32_t k = 0U; k < BLOCK_SIZE; k++) {
        float s = sinf(two_pi * ((float)(k + BLOCK_SIZE)/2.0f)/( (float)BLOCK_SIZE));
        uint32_t duty = duty_to_cr(0.50f + (0.40f * s));
        audio_buffer_0[1][k] = (duty / 2);
    }
}