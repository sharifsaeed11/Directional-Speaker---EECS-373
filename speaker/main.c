// Two instruction cards telling DAC DMA which buffer to play.
static XMC_DMA_LLI_t blocks[NUM_SPEAKERS][2]; // 2 buffers for each speaker output


void build_instruction_cards(void){

  //build 2 instruction cards
  for (unsigned speaker = 0; speaker < NUM_SPEAKERS; speaker++) {
    for (unsigned i = 0; i < 2; ++i){

        // First sample for each block
        blocks[speaker][i].src_addr = (uint32_t)&audio_buffer[i][speaker];
        // Create a linked list of all the blocks
        blocks[speaker][i].llp = (i < 1) ? &blocks[speaker][i + 1] : &blocks[speaker][0];
        
        // Transfer settings from Device Configurator
        if (speaker == 0)      blocks[speaker][i].control = gpdma_0_ch_0_config.control;
        else if (speaker == 1) blocks[speaker][i].control = gpdma_0_ch_1_config.control;
        else if (speaker == 2) blocks[speaker][i].control = gpdma_0_ch_2_config.control;
        else if (speaker == 3) blocks[speaker][i].control = gpdma_0_ch_3_config.control;
        else if (speaker == 4) blocks[speaker][i].control = gpdma_0_ch_4_config.control;
        else if (speaker == 5) blocks[speaker][i].control = gpdma_0_ch_5_config.control;
        else if (speaker == 6) blocks[speaker][i].control = gpdma_0_ch_6_config.control;
        else if (speaker == 7) blocks[speaker][i].control = gpdma_0_ch_7_config.control;

        blocks[speaker][i].block_size = 256;

        // The two block should link to each other
        blocks[speaker][i].enable_src_linked_list = 1;
        
    }

  }

  // Point DMA at the first instruction card.
  XMC_DMA_CH_SetLinkedListPointer(XMC_DMA0, speaker0_dma_ch, blocks); // just one channel for now
//   XMC_DMA_CH_SetLinkedListPointer(XMC_DMA0, speaker1_dma_ch, blocks);
//   XMC_DMA_CH_SetLinkedListPointer(XMC_DMA0, speaker2_dma_ch, blocks);
//   XMC_DMA_CH_SetLinkedListPointer(XMC_DMA0, speaker3_dma_ch, blocks);
//   XMC_DMA_CH_SetLinkedListPointer(XMC_DMA0, speaker4_dma_ch, blocks);
//   XMC_DMA_CH_SetLinkedListPointer(XMC_DMA0, speaker5_dma_ch, blocks);
//   XMC_DMA_CH_SetLinkedListPointer(XMC_DMA0, speaker6_dma_ch, blocks);
//   XMC_DMA_CH_SetLinkedListPointer(XMC_DMA0, speaker7_dma_ch, blocks);

}




// CCU80 offset 40020000
// CCU80_SLICE0_CR1S = 0x4002023C (0x40020100 + 0x013C = 0x4002023C)
#define CCU80_SLICE0_CR1S CCU80_CC80_BASE + 0x013C




inline uint32_t pcm_to_center_aligned_compare_val(uint32_t pcm_val){

    uint32_t result = (pcm_val * CENTER_ALIGNED_TIMER_PERIOD) >> 16;

    return CENTER_ALIGNED_TIMER_PERIOD - result;

}

inline uint32_t pcm_to_edge_aligned_compare_val(uint32_t pcm_val){

    uint32_t result = (pcm_val * EDGE_ALIGNED_TIMER_PERIOD) >> 16;

    return EDGE_ALIGNED_TIMER_PERIOD - result;

}


