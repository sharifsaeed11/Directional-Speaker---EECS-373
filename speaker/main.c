#define PWM_PERIOD_TICKS 3600
static uint32_t duty_to_cr(float duty)
{
  if (duty < 0.0f) { duty = 0.0f; }
  if (duty > 1.0f) { duty = 1.0f; }
  uint32_t on_ticks = (uint32_t)((duty * (float)PWM_PERIOD_TICKS) + 0.5f);
  if (on_ticks > PWM_PERIOD_TICKS) { on_ticks = PWM_PERIOD_TICKS; }
  return PWM_PERIOD_TICKS - on_ticks;
}

